const FALLBACK =
  'По этому вопросу у меня нет точных данных в базе знаний установки ЭЛОУ-АВТ. Уточните узел (ЭЛОУ, атмосферный блок, печь П-2, колонна К-2, блок ГДМ) или параметр — вода в нефти, давление, температура, уровень — и я подскажу регламент действий.'

function answerFor(question: string): string {
  const q = question.toLowerCase()
  let best: { score: number; answer: string } | null = null
  for (const entry of KNOWLEDGE) {
    const score = entry.keywords.reduce((s, kw) => (q.includes(kw) ? s + 1 : s), 0)
    if (score > 0 && (!best || score > best.score)) {
      best = { score, answer: entry.answer }
    }
  }
  return best?.answer ?? FALLBACK
}

export const aiHandlers = [
  // Real path: POST /api/v1/ai/chat  (gateway → ai /v1/chat)
  http.post('/api/v1/ai/chat', async ({ request }) => {
    const body = (await request.json()) as { question?: string; messages?: ChatMessage[] }
    // Accept both the new {question} shape and old {messages} shape for compatibility.
    const question =
      body.question ??
      [...(body.messages ?? [])].reverse().find((m) => m.role === 'user')?.content ??
      ''
    await delay(600 + Math.random() * 500)
    return HttpResponse.json({ answer: answerFor(question) })
  }),
]
